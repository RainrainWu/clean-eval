"""What the adaptors need from the outside world: one protocol per gateway they are given. The gateways of the
external layer implement them; the adaptors translate between them and the use cases' ports, and never reach outside
the process themselves."""
from typing import Optional, Protocol


class Git(Protocol):
    """The git repository the sources read."""

    def toplevel(self) -> str: ...
    def rev_parse(self, rev: str, short: bool = False) -> str: ...
    def branch(self) -> str: ...
    def repo_name(self) -> str: ...
    def ls_files(self) -> list: ...
    def ls_tree(self, rev: str) -> list:
        """[(path, blob id, size)] of the files at `rev`."""
    def read_blobs(self, blob_ids: list) -> dict:
        """{blob id: text}."""


class FileSystem(Protocol):
    """Files and folders, and the path strings that name them."""
    sep: str

    def join(self, *parts: str) -> str: ...
    def parent(self, path: str) -> str: ...
    def name(self, path: str) -> str: ...
    def relative(self, path: str, start: str) -> str: ...
    def absolute(self, path: str) -> str: ...
    def exists(self, path: str) -> bool: ...
    def lexists(self, path: str) -> bool: ...
    def is_file(self, path: str) -> bool: ...
    def is_dir(self, path: str) -> bool: ...
    def is_link(self, path: str) -> bool: ...
    def size(self, path: str) -> int: ...
    def files_under(self, top: str) -> list: ...
    def glob(self, folder: str, pattern: str) -> list: ...
    def read_text(self, path: str) -> str:
        """The file's text; HeatmapError when it can't be read."""
    def write_text(self, path: str, text: str) -> None: ...
    def append_text(self, path: str, text: str) -> None: ...
    def same_content(self, a: str, b: str) -> bool: ...
    def make_dirs(self, path: str) -> None: ...
    def copy_file(self, src: str, dst: str) -> None: ...
    def copy_tree(self, src: str, dst: str) -> None: ...
    def remove(self, path: str) -> None: ...
    def remove_tree(self, path: str) -> None: ...


class Database(Protocol):
    """A read-only database (a context manager that closes it)."""

    def rows(self, query: str, params: tuple = ()) -> list: ...
    def close(self) -> None: ...


class GraphBuilder(Protocol):
    """The code-review-graph CLI."""

    def build(self, repo_root: str, data_dir: str) -> None:
        """Build the graph of a working tree into `data_dir` (graph.db)."""


class DatabaseOpener(Protocol):
    def __call__(self, path: str) -> Database: ...


class Executable(Protocol):
    def __call__(self, name: str, search_path: Optional[str] = None) -> Optional[str]: ...
